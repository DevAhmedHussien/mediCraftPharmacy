#!/usr/bin/env python3
"""Responsive variants and blur placeholders for every 16:9 hero.

There is no image optimiser (see next.config.js), so a hero is one 2560px
file unless we cut the smaller ones ourselves. For each
public/images/hero/<name>.webp this writes <name>-640/-1080/-1600.webp
beside it (never upscaled) and regenerates lib/media-blur.ts, a map from
file name to a ~24px WebP data URI painted while the real image loads.

Re-run after replacing a hero photograph:

    python3 scripts/hero-variants.py        # needs Pillow (pip install pillow)

then bump `V` in lib/media.ts so browsers fetch the new files.
"""
import base64
import io
import re
import sys
from pathlib import Path

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
HERO = ROOT / "public" / "images" / "hero"
WIDTHS = (640, 1080, 1600)
VARIANT = re.compile(r"-(%s)$" % "|".join(map(str, WIDTHS)))


def main() -> int:
    blur: dict[str, str] = {}
    sources = sorted(p for p in HERO.glob("*.webp") if not VARIANT.search(p.stem))
    for src in sources:
        im = Image.open(src).convert("RGB")
        for w in WIDTHS:
            out = im if im.width <= w else im.resize((w, round(w * im.height / im.width)), Image.LANCZOS)
            out.save(HERO / f"{src.stem}-{w}.webp", "WEBP", quality=86, method=6)
        tiny = im.resize((24, round(24 * im.height / im.width)), Image.LANCZOS).filter(ImageFilter.GaussianBlur(0.6))
        buf = io.BytesIO()
        tiny.save(buf, "WEBP", quality=60)
        blur[src.stem] = "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()
        print(f"{src.name}: {im.width}x{im.height} -> {', '.join(map(str, WIDTHS))}")

    lines = [
        "/* Generated by scripts/hero-variants.py — do not edit by hand.",
        "   A ~24px blurred copy of each hero, painted behind the <img> so the",
        "   frame shows the photograph's colours before the file arrives. */",
        "",
        "export const heroBlur: Record<string, string> = {",
        *[f'  "{k}":\n    "{v}",' for k, v in blur.items()],
        "};",
        "",
    ]
    (ROOT / "lib" / "media-blur.ts").write_text("\n".join(lines))
    print(f"lib/media-blur.ts: {len(blur)} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
